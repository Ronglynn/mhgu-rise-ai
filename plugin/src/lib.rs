                                if heap_ok(p + 0x64) {
                                    (rd(p + 0x40), rd(p + 0x44), rd(p + 0x48), rd(p + 0x4C),
                                     rd(p + 0x50), rd(p + 0x54), rd(p + 0x58), rd(p + 0x60))
                                } else { (0u32, 0u32, 0u32, 0u32, 0u32, 0u32, 0u32, 0u32) };
