            Z_LOG = 0; ZP_LOG = 0; ZS_LOG = 0; ZT_LOG = 0;
            AE_LOG = 0; QX_LOG = 0; B2_LOG = 0; COMBO_LOG = 0; AR_LOG = 0; HB_LOG = 0;
