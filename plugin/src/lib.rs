#[inline(always)]
unsafe fn rd(a: u32) -> u32 { unsafe { core::ptr::read_volatile(a as *const u32) } }
#[inline(always)]
unsafe fn rd8(a: u32) -> u8 { unsafe { core::ptr::read_volatile(a as *const u8) } }
#[inline(always)]
unsafe fn rd16(a: u32) -> u16 { unsafe { core::ptr::read_volatile(a as *const u16) } }
// v55：v54 的 wr8/wr16 直接写状态字方案已被 P48 实机证伪并删除。
// 本版**零游戏内存写入**，强制只通过 h_stamina 放大 delta 参数实现。
#[inline(always)]
fn heap_ok(p: u32) -> bool { p >= HEAP_LO && p < HEAP_HI }
#[inline(always)]
fn script_ok(p: u32) -> bool { p >= SCRIPT_LO && p < SCRIPT_HI }
#[inline(always)]
fn adiff(a: u32, b: u32) -> u32 { if a >= b { a - b } else { b - a } }
#[inline(always)]
fn fnv_push(h: u32, b: u8) -> u32 { (h ^ (b as u32)).wrapping_mul(0x0100_0193) }
const FNV0: u32 = 0x811C_9DC5;

#[inline(always)]
fn ins_len(op: u8, sub: u8) -> u32 {
    if op > 0xA6 { return 0xFF; }
    let t = LEN[op as usize];
    if t & 0x80 == 0 { return t as u32; }
    if sub == 1 {
        let hi = t & 0xF0;
        return if hi == 0x90 { 3 } else if hi == 0xA0 { 4 } else if hi == 0xB0 { 5 } else { 2 };
    }
    if sub == 0 { return (t as u32 + 1) & 15; }
    1
}

#[inline(always)]
unsafe fn ident(a0: u32) -> u32 {
    unsafe {
        if !heap_ok(a0) { return 0; }
        let act = rd(a0 + 0x1428);
        if heap_ok(act) { act } else { 0 }
    }
}

/// v41：把出现过的 mon 注册进每帧扫描槽（最多 NMON 只，先到先得）。
/// v42：返回槽号，供 F 行标注写入对象（与 C 行扫描槽同源）。
#[inline(always)]
unsafe fn reg_mon(m: u32) -> u32 {
    unsafe {
        if !heap_ok(m) { return 0xFFFF_FFFF; }
        let mut i = 0usize;
        while i < NMON {
            let x = CMON[i];
            if x == m { return i as u32; }
            i += 1;
        }
        i = 0;
        while i < NMON {
            let x = CMON[i];
            if x == 0 { CMON[i] = m; CFP[i] = 0xFFFF_FFFF; return i as u32; }
            i += 1;
        }
        0xFFFF_FFFF
    }
}

