/// 纯只读：从已挂载的 `h_matcher` 参数与 `sub=*(mon+0x1428)` 几何字段取样。
/// 不调用游戏函数、不写游戏内存、不改变任何返回值。
unsafe fn dist_probe(f: u32, mon: u32, ip: u32, op: u8, md: u32,
                     val: u32, ret: u32) {
    unsafe {
        Z_N = Z_N.wrapping_add(1);
        if Z_LOG >= MAX_Z || LOGN >= MAXLOG { return; }

        // 1) case 阈值序列：主路径 find_begin -> 256B 回退 -> near 扫描
        let mut cs = [Case { pos: 0, sig: 0, w: 0 }; MAXCASE];
        let mut n: usize = 0;
        let mut blk: u32 = 0;
        let mut src: u32 = 0;      // 1=begin / 2=near / 0=未解析
        if script_ok(ip) {
            blk = find_begin(ip, op);
            if blk != 0 { n = scan_cases(blk, op, &mut cs); }
            if n < 2 {
                let low = if ip > 256 { ip - 256 } else { SCRIPT_LO };
                let mut q = if ip > 1 { ip - 1 } else { ip };
                while q > low {
                    if rd8(q) == op && rd8(q + 1) == 0 {
                        let t = scan_cases(q, op, &mut cs);
                        if t >= 2 { blk = q; n = t; break; }
                    }
                    q -= 1;
                }
            }
            if n >= 2 { src = 1; }
            else {
                blk = 0;
                n = scan_cases_near(ip, op, &mut cs);
                if n >= 2 { src = 2; } else { n = 0; }
            }
        }
        let t0 = if n > 0 { cs[0].w } else { 0 };
        let t1 = if n > 1 { cs[1].w } else { 0 };
        let t2 = if n > 2 { cs[2].w } else { 0 };
        let t3 = if n > 3 { cs[3].w } else { 0 };

        // 2) 命中档位：matcher 返回「到选中 case 的字节距离」
        let guess = ip.wrapping_add(ret);
        let mut hit: i32 = -1;
        let mut bestd: u32 = u32::MAX;
        let mut k = 0usize;
        while k < n {
            let d0 = adiff(cs[k].pos, guess);
            let d1 = adiff(cs[k].pos.wrapping_add(1), guess);
            let dd = if d0 < d1 { d0 } else { d1 };
            if dd < bestd { bestd = dd; hit = k as i32; }
            k += 1;
        }
        if bestd > MATCH_TOL { hit = -1; }

        // 3) v59：即使 case 序列解析失败，也留下命中点和原始字节
        let mut ts: u32 = 0xFF;    // 命中 case 的阈值操作数；0xFF = 未定
        if hit >= 0 { ts = cs[hit as usize].w; }
        else {
            let mut q = guess.wrapping_sub(2);
            let mut c = 0u32;
            while c < 6 {
                if rd8(q) == op && rd8(q + 1) == 1 {
                    ts = rd8(q + 2) as u32; break;
                }
                q = q.wrapping_add(1); c += 1;
            }
        }
        let mut rb = [0u8; 8];
        let q0 = guess.wrapping_sub(2);
        let mut c = 0usize;
        while c < 8 { rb[c] = rd8(q0.wrapping_add(c as u32)); c += 1; }
        let r0 = u32::from_le_bytes([rb[0], rb[1], rb[2], rb[3]]);
        let r1 = u32::from_le_bytes([rb[4], rb[5], rb[6], rb[7]]);

        let mon_ok = heap_ok(mon) && mon + 0x2600 < HEAP_HI;
        let st3 = if mon_ok { mon_state(mon) } else { 0 };
        Z_LOG = Z_LOG.wrapping_add(1);
        LOGN = LOGN.wrapping_add(1);
        let lg = LOGN;
        info!("[rai] Z f={} op={:02X} md={} val={:08X} ip={:08X} blk={:08X} nc={} src={} t0={} t1={} t2={} t3={} hit={} ts={} ret={} st3={} g={:08X} r0={:08X} r1={:08X} log={}",
              f, op, md, val, ip, blk, n, src, t0, t1, t2, t3, hit, ts,
              ret, st3, guess, r0, r1, lg);

        // v61：TABLE 型距离块读运行时 dttune 阈值链（纯只读，失败静默跳过）
        let mut is_table = false;
        let mut ti = 0usize;
        while ti < TABLE_MODES.len() {
            if md == TABLE_MODES[ti] { is_table = true; break; }
            ti += 1;
        }
        if is_table {
            let ba = if blk != 0 && script_ok(blk) { rd8(blk + 2) as u32 } else { 0xFF };
            dist_table_probe(f, mon, ip, md, blk, ba);
        }

        // 4) 低频几何快照 + 脚本指针扫描（纯只读）
        if Z_N % ZP_EVERY == 0 && ZP_LOG < MAX_ZP && LOGN < MAXLOG && mon_ok {
            let sub = rd(mon + 0x1428);
            if heap_ok(sub) && sub + 0x310 < HEAP_HI {
                let a30 = rd(sub + 0x30);
                let a34 = rd(sub + 0x34);
                let a38 = rd(sub + 0x38);
                let a40 = rd(sub + 0x40);
                let a44 = rd(sub + 0x44);
                let a48 = rd(sub + 0x48);
                let e0 = rd(sub + 0x2E8);
                let e2 = rd(sub + 0x2F0);
                let e4 = rd(sub + 0x2F8);
                let hd = rd16(sub + 0x54);
                let cmd = rd(mon + 0x2588);
                let ent = if heap_ok(cmd) && cmd + 0x80 < HEAP_HI { rd(cmd + 0x78) } else { 0 };
                ZP_LOG = ZP_LOG.wrapping_add(1);
                LOGN = LOGN.wrapping_add(1);
                let lg2 = LOGN;
                info!("[rai] ZP f={} mon={:08X} sub={:08X} a30={:08X} a34={:08X} a38={:08X} a40={:08X} a44={:08X} a48={:08X} e0={:08X} e2={:08X} e4={:08X} hd={:04X} cmd={:08X} ent={:08X} log={}",
                      f, mon, sub, a30, a34, a38, a40, a44, a48,
                      e0, e2, e4, hd, cmd, ent, lg2);

                // v59 ZS：a0±0x2000 扫落在 script 段的指针候选，用实机数据
                // 定位真正的 em/cmd 基址（P55 证明 +0x2588 硬编码不成立）。
                if ZS_LOG < MAX_ZS && LOGN < MAXLOG {
                    ZS_LOG = ZS_LOG.wrapping_add(1);
                    LOGN = LOGN.wrapping_add(1);
                    let lo = if mon > 0x2000 { mon - 0x2000 } else { HEAP_LO };
                    let mut hi = mon.wrapping_add(0x2000);
                    if hi > HEAP_HI - 4 { hi = HEAP_HI - 4; }
                    let mut p = lo & !3u32;
                    let mut off = [0i32; 6];
                    let mut pv = [0u32; 6];
                    let mut cnt = 0usize;
                    while p < hi && cnt < 6 {
                        let v = rd(p);
                        if v >= SCRIPT_LO && v < SCRIPT_HI {
                            off[cnt] = (p as i32).wrapping_sub(mon as i32);
                            pv[cnt] = v;
                            cnt += 1;
                            p = p.wrapping_add(0x40);
                        } else { p = p.wrapping_add(4); }
                    }
                    let lg3 = LOGN;
                    info!("[rai] ZS f={} mon={:08X} n={} o0={} v0={:08X} o1={} v1={:08X} o2={} v2={:08X} o3={} v3={:08X} o4={} v4={:08X} o5={} v5={:08X} log={}",
                          f, mon, cnt, off[0], pv[0], off[1], pv[1], off[2], pv[2],
                          off[3], pv[3], off[4], pv[4], off[5], pv[5], lg3);
                }
            }
        }
    }
}

